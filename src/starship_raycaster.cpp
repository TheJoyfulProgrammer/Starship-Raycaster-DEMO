std::string App::currentStatusLine() const
{
    auto presetName = [&]()->std::string {
        using P = star::pal::PalettePreset;
        switch (palettePreset_)
        {
            case P::Grayscale:  return "Grayscale(0)";
            case P::Perceptual: return "Perceptual(1)";
            case P::Green33: return "0..#33FF33(2)";
            case P::Green66: return "0..#66FF66(3)";
            case P::GoldCC:  return "0..#FFCC00(4)";
            case P::GoldB0:  return "0..#FFB000(5)";
            case P::VGA256:  return "VGA256(6)";
            case P::ColorTheory: return "ColorTheory(7)";
            case P::MutedTeal: return "0..#2F7875(8)";
            case P::Vermilion: return "0..#C04D3E(9)";
            default: return "Custom";
        }
    }();

    auto ditherName = [&]()->std::string{
        using D = star::pal::DitherMode;
        if (!ditheringEnabled_) return "OFF";
        switch (ditherMode_)
        {
			case D::FloydSteinberg: return "Floyd-Steinberg(F4)";
			case D::FloydSteinbergLumaOnly: return "Floyd-Luma(F5)";
			case D::FloydSteinbergBlock: return "Floyd-Block(F6)";
            case D::Atkinson: return "Atkinson(F7)";
            case D::OrderedBayer: return "Ordered/Bayer(F8)";
            case D::JarvisJudiceNinke: return "JJN(F9)";
            case D::Stucki: return "Stucki(F10)";
            case D::Riemersma: return "Riemersma(F11)";
            case D::BlueNoise: return "BlueNoise(F12)";
            default: return "None";
        }
    }();

    std::string fx = effects_.empty() ? "(no effects)" : effects_[activeEffect_].name;

    std::string ct;
    if (palettePreset_ == star::pal::PalettePreset::ColorTheory)
    {
        ct = " | Hue=" + std::to_string((int)ctHue_) +
             " Luma=" + std::to_string((int)ctLuma_) +
		     " Scheme=" + std::to_string((int)ctScheme_) + " (PgUp/PgDn)";
    }

    std::string ditherExtra;
    if (ditheringEnabled_)
    {
        int pct = (int)std::lround(ditherStrength_ * 100.0);
        ditherExtra += " | Strength=" + std::to_string(pct) + "% (Ctrl+/-)";
        if (ditherMode_ == star::pal::DitherMode::BlueNoise)
            ditherExtra += " | BN-drift=" + std::string(bnDriftEnabled_ ? "ON" : "OFF") + " (Ctrl+Shift+B)";
    }

    std::string gameExtra;
    gameExtra += " | Game=" + std::string(gameEnabled_ ? "ON" : "OFF") + " (J)";
    if (gameEnabled_)
    {
        int apct = (int)std::lround(gameAlpha_ * 100.0);
        gameExtra += " | Alpha=" + std::to_string(apct) + "% (,/.)";
        gameExtra += " | Move=WASD Run=Shift Turn=Arrows Door=E Lock=L Regen=R";
    }

    std::string modeExtra;
    modeExtra += " | PalIdx=" + std::string(paletteIndexMode_ ? "ON" : "OFF") + " (F)";

    std::string overlayExtra;
    overlayExtra += " | HealthVig=" + std::string(healthVignetteEnabled_ ? "ON" : "OFF") + " (H)";
    overlayExtra += " | Vig=" + std::to_string((int)std::lround(healthVignetteSizePx_)) + "px (F1/F2)";
    overlayExtra += " | GUI=" + std::string(guiEnabled_ ? "ON" : "OFF") + " (G)";
    if (guiEnabled_)
    {
        overlayExtra += " | Map=" + std::string(fullMapWanted_ ? "ON" : "OFF") + " (M)";
        overlayExtra += " | CRT=" + std::to_string((int)mapCrtMode_) + " (B)";
        overlayExtra += " | HP=" + std::to_string(hudHealth_) + " AM=" + std::to_string(hudAmmo_);
    }

    return std::string(APP_NAME) + " | Shader=[" + fx + "] ([ ])" + modeExtra + " | Palette=" + presetName +
           " | Colors=" + std::to_string(colorsToUse_) + " (Ctrl+F1/F2)" +
           " | Pixel=" + std::to_string(pixelSize_) + " (+/-)" +
           " | Dither=" + ditherName + " (F3 toggle)" + ditherExtra + ct + overlayExtra + gameExtra;
}

