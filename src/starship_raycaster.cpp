App::App(SDL_Window* window) : window_(window)
{
    // Default CPU palette (in case perceptual has no data yet)
    cpuPalette_ = star::pal::buildGradient({0,0,0}, {255,255,255});
    cpuLut_ = star::pal::buildLut33(cpuPalette_, colorsToUse_);

    // Game overlay state is CPU-only; initialize before Vulkan so we can upload immediately.
    initGame();

    initVulkan();

    // Start with mouse captured (FPS-style), but allow TAB to release.
    setMouseCaptured(true);

    SDL_SetWindowTitle(window_, currentStatusLine().c_str());
}

