std::vector<char> App::readFile(const std::string& filename)
{
    // We want shader/assets loading to be insensitive to the *working directory*.
    // We'll try a small set of reasonable search roots:
    //  1) As-given (relative to CWD)
    //  2) Relative to the executable directory (SDL_GetBasePath)
    //  3) One and two levels up from executable dir (handles multi-config layouts: build/Release/...)
    namespace fs = std::filesystem;

    std::vector<fs::path> candidates;
    candidates.push_back(fs::path(filename));

    // SDL3 returns a const char* here (no SDL_free needed).
    if (const char* base = SDL_GetBasePath(); base)
    {
        fs::path bp = fs::path(base);

        candidates.push_back(bp / filename);
        candidates.push_back(bp / ".." / filename);
        candidates.push_back(bp / ".." / ".." / filename);
    }

    std::ifstream f;
    for (const auto& p : candidates)
    {
        f.open(p, std::ios::ate | std::ios::binary);
        if (f)
        {
            break;
        }
        f.clear();
    }

    if (!f)
    {
        std::string msg = "Failed to open file: " + filename + "\nSearched:";
        for (const auto& p : candidates) msg += "\n  - " + p.string();
        throw std::runtime_error(msg);
    }

    size_t size = (size_t)f.tellg();
    std::vector<char> buf(size);
    f.seekg(0);
    f.read(buf.data(), size);
    return buf;
}

VkShaderModule App::createShaderModuleFromFile(const std::string& filePath)
{
    auto code = readFile(filePath);

    VkShaderModuleCreateInfo ci{VK_STRUCTURE_TYPE_SHADER_MODULE_CREATE_INFO};
    ci.codeSize = code.size();
    ci.pCode = reinterpret_cast<const uint32_t*>(code.data());

    VkShaderModule mod = VK_NULL_HANDLE;
    vkCheck(vkCreateShaderModule(device_, &ci, nullptr, &mod), ("vkCreateShaderModule: " + filePath).c_str());
    return mod;
}

// -------------------- memory helpers --------------------

uint32_t App::findMemoryType(uint32_t typeFilter, VkMemoryPropertyFlags properties)
{
    VkPhysicalDeviceMemoryProperties memProps{};
    vkGetPhysicalDeviceMemoryProperties(physicalDevice_, &memProps);

    for (uint32_t i=0;i<memProps.memoryTypeCount;++i)
    {
        if ((typeFilter & (1u<<i)) && (memProps.memoryTypes[i].propertyFlags & properties) == properties)
            return i;
    }
    throw std::runtime_error("Failed to find suitable memory type");
}

void App::createBuffer(VkDeviceSize size, VkBufferUsageFlags usage, VkMemoryPropertyFlags properties,
                       VkBuffer& buffer, VkDeviceMemory& memory, void** mapped)
{
    VkBufferCreateInfo bci{VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO};
    bci.size = size;
    bci.usage = usage;
    bci.sharingMode = VK_SHARING_MODE_EXCLUSIVE;

    vkCheck(vkCreateBuffer(device_, &bci, nullptr, &buffer), "vkCreateBuffer");

    VkMemoryRequirements req{};
    vkGetBufferMemoryRequirements(device_, buffer, &req);

    VkMemoryAllocateInfo ai{VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO};
    ai.allocationSize = req.size;
    ai.memoryTypeIndex = findMemoryType(req.memoryTypeBits, properties);

    vkCheck(vkAllocateMemory(device_, &ai, nullptr, &memory), "vkAllocateMemory(buffer)");
    vkCheck(vkBindBufferMemory(device_, buffer, memory, 0), "vkBindBufferMemory");

    if (mapped)
    {
        vkCheck(vkMapMemory(device_, memory, 0, size, 0, mapped), "vkMapMemory(buffer)");
    }
}

void App::destroyBuffer(VkBuffer& buffer, VkDeviceMemory& memory, void** mapped)
{
    if (mapped && *mapped)
    {
        vkUnmapMemory(device_, memory);
        *mapped = nullptr;
    }
    if (buffer) vkDestroyBuffer(device_, buffer, nullptr);
    if (memory) vkFreeMemory(device_, memory, nullptr);
    buffer = VK_NULL_HANDLE;
    memory = VK_NULL_HANDLE;
}

