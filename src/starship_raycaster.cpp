    inline void putPixel(std::vector<uint8_t>& rgba, int W, int H, int x, int y,
                         uint8_t r, uint8_t g, uint8_t b, uint8_t a)
    {
        if (x < 0 || y < 0 || x >= W || y >= H) return;
        const int i = (y * W + x) * 4;
        rgba[i + 0] = r;
        rgba[i + 1] = g;
        rgba[i + 2] = b;
        rgba[i + 3] = a;
    }

    inline void blendPixel(std::vector<uint8_t>& rgba, int W, int H, int x, int y,
                           uint8_t r, uint8_t g, uint8_t b, uint8_t a)
    {
        if (a == 0) return;
        if (x < 0 || y < 0 || x >= W || y >= H) return;
        const int i = (y * W + x) * 4;
        const uint8_t dstA = rgba[i + 3];
        const uint16_t srcA = a;
        const uint16_t invA = 255 - a;

        // Straight-alpha over.
        rgba[i + 0] = (uint8_t)((r * srcA + rgba[i + 0] * invA) / 255);
        rgba[i + 1] = (uint8_t)((g * srcA + rgba[i + 1] * invA) / 255);
        rgba[i + 2] = (uint8_t)((b * srcA + rgba[i + 2] * invA) / 255);
        rgba[i + 3] = (uint8_t)std::min(255, (int)dstA + (int)srcA - (int)(dstA * srcA) / 255);
    }

    inline void fillRectRGBA(std::vector<uint8_t>& rgba, int W, int H, int x0, int y0, int x1, int y1,
                             uint8_t r, uint8_t g, uint8_t b, uint8_t a)
    {
        if (x0 > x1) std::swap(x0, x1);
        if (y0 > y1) std::swap(y0, y1);
        x0 = std::max(0, x0); y0 = std::max(0, y0);
        x1 = std::min(W - 1, x1); y1 = std::min(H - 1, y1);
        for (int y = y0; y <= y1; ++y)
            for (int x = x0; x <= x1; ++x)
                blendPixel(rgba, W, H, x, y, r, g, b, a);
    }

    inline void drawRectRGBA(std::vector<uint8_t>& rgba, int W, int H, int x0, int y0, int x1, int y1,
                             uint8_t r, uint8_t g, uint8_t b, uint8_t a)
    {
        if (x0 > x1) std::swap(x0, x1);
        if (y0 > y1) std::swap(y0, y1);
        for (int x = x0; x <= x1; ++x)
        {
            blendPixel(rgba, W, H, x, y0, r, g, b, a);
            blendPixel(rgba, W, H, x, y1, r, g, b, a);
        }
        for (int y = y0; y <= y1; ++y)
        {
            blendPixel(rgba, W, H, x0, y, r, g, b, a);
            blendPixel(rgba, W, H, x1, y, r, g, b, a);
        }
    }

    [[maybe_unused]] inline void blitDigit5x7(std::vector<uint8_t>& rgba, int W, int H,
                             int x0, int y0, int scale,
                             int digit, uint8_t r, uint8_t g, uint8_t b, uint8_t a)
    {
        const auto& rows = DIGITS_5x7[digit];
        for (int y = 0; y < 7; ++y)
        {
            for (int x = 0; x < 5; ++x)
            {
                if ((rows[y] >> (4 - x)) & 1)
                {
                    for (int sy = 0; sy < scale; ++sy)
                        for (int sx = 0; sx < scale; ++sx)
                            putPixel(rgba, W, H, x0 + x * scale + sx, y0 + y * scale + sy, r, g, b, a);
                }
            }
        }
    }
// Render digits 0..9 from a TTF into tiles [0..9] (row 0) as WHITE with grayscale alpha.
// Returns true if FreeType + font load succeeded and digits were drawn.
bool blitDigitsFromFreeType(std::vector<uint8_t>& rgba, int W, int H,
                            int TILE, int GRID, const std::string& fontRelPath)
{
    namespace fs = std::filesystem;

    FT_Library ft = nullptr;
    if (FT_Init_FreeType(&ft) != 0) return false;

    FT_Face face = nullptr;

    // Search for the font similar to App::readFile() search roots.
    std::vector<fs::path> candidates;
    candidates.push_back(fs::path(fontRelPath));
    if (const char* base = SDL_GetBasePath(); base)
    {
        fs::path bp = fs::path(base);
        candidates.push_back(bp / fontRelPath);
        candidates.push_back(bp / ".." / fontRelPath);
        candidates.push_back(bp / ".." / ".." / fontRelPath);
    }

    fs::path chosen;
    for (const auto& p : candidates)
    {
        std::error_code ec;
        if (fs::exists(p, ec) && !ec)
        {
            chosen = p;
            break;
        }
    }

    if (chosen.empty())
    {
        FT_Done_FreeType(ft);
        return false;
    }

    if (FT_New_Face(ft, chosen.string().c_str(), 0, &face) != 0)
    {
        FT_Done_FreeType(ft);
        return false;
    }

    // Pick a size that fits comfortably in 32x32 tiles.
    // (Height 28 gives room for descenders/antialias.)
    FT_Select_Charmap(face, FT_ENCODING_UNICODE);
    FT_Set_Pixel_Sizes(face, 0, 28);

    auto plot = [&](int x, int y, uint8_t cov)
    {
        if (cov == 0) return;
        if (x < 0 || y < 0 || x >= W || y >= H) return;
        size_t i = (size_t(y) * size_t(W) + size_t(x)) * 4;
        // White glyph with grayscale alpha.
        rgba[i + 0] = 255;
        rgba[i + 1] = 255;
        rgba[i + 2] = 255;
        rgba[i + 3] = (uint8_t)std::max<int>(rgba[i + 3], cov);
    };

    for (int d = 0; d < 10; ++d)
    {
        char ch = char('0' + d);
        if (FT_Load_Char(face, ch, FT_LOAD_RENDER) != 0)
            continue;

        FT_GlyphSlot g = face->glyph;
        const FT_Bitmap& bm = g->bitmap;

        const int tx = d % GRID;
        const int ty = 0;
        const int x0 = tx * TILE;
        const int y0 = ty * TILE;

        // Simple centering (good enough for digits; keeps code robust across fonts).
        const int left = x0 + (TILE - int(bm.width)) / 2;
        const int top  = y0 + (TILE - int(bm.rows)) / 2;

        for (unsigned int y = 0; y < bm.rows; ++y)
        {
            for (unsigned int x = 0; x < bm.width; ++x)
            {
                uint8_t cov = 0;
                if (bm.pixel_mode == FT_PIXEL_MODE_GRAY)
                {
                    cov = bm.buffer[int(y) * bm.pitch + int(x)];
                }
                else if (bm.pixel_mode == FT_PIXEL_MODE_MONO)
                {
                    uint8_t byte = bm.buffer[int(y) * bm.pitch + int(x >> 3)];
                    cov = (byte & (0x80u >> (x & 7u))) ? 255 : 0;
                }
                plot(left + int(x), top + int(y), cov);
            }
        }
    }

    FT_Done_Face(face);
    FT_Done_FreeType(ft);
    return true;
}

    inline bool setVariableFontWeight(FT_Library ft, FT_Face face, int wght)
    {
        FT_MM_Var* mm = nullptr;
        if (FT_Get_MM_Var(face, &mm) != 0 || !mm) return false;

        std::vector<FT_Fixed> coords(mm->num_axis);
        for (FT_UInt i = 0; i < mm->num_axis; ++i)
            coords[i] = mm->axis[i].def;

        const FT_ULong WGHT = FT_MAKE_TAG('w','g','h','t');
        bool found = false;
        for (FT_UInt i = 0; i < mm->num_axis; ++i)
        {
            if (mm->axis[i].tag == WGHT)
            {
                FT_Fixed v = (FT_Fixed)(wght * 65536);
                v = std::max(mm->axis[i].minimum, std::min(mm->axis[i].maximum, v));
                coords[i] = v;
                found = true;
                break;
            }
        }

        if (found)
            (void)FT_Set_Var_Design_Coordinates(face, mm->num_axis, coords.data());

        FT_Done_MM_Var(ft, mm);
        return found;
    }

    inline void renderTextLine(FT_Library ft, FT_Face face,
                               std::vector<uint8_t>& rgba, int W, int H,
                               int x, int yTop,
                               const std::string& text,
                               int px, int weight,
                               uint8_t r, uint8_t g, uint8_t b, uint8_t a)
    {
        // yTop is a top coordinate; compute baseline using ascender.
        bool varOk = setVariableFontWeight(ft, face, weight);
        (void)varOk;
        (void)FT_Set_Pixel_Sizes(face, 0, (FT_UInt)px);

        const int asc = (int)(face->size ? (face->size->metrics.ascender >> 6) : (px));
        const int baseline = yTop + asc;
        int penX = x;

        for (unsigned char ch : text)
        {
            if (ch == '\n') { penX = x; continue; }
            if (FT_Load_Char(face, ch, FT_LOAD_DEFAULT) != 0)
                continue;

            // Fallback bold if variable weight isn't available.
            if (!varOk && weight >= 700)
                FT_GlyphSlot_Embolden(face->glyph);

            if (FT_Render_Glyph(face->glyph, FT_RENDER_MODE_NORMAL) != 0)
                continue;

            const FT_GlyphSlot slot = face->glyph;
            const FT_Bitmap& bm = slot->bitmap;
            const int left = penX + slot->bitmap_left;
            const int top  = baseline - slot->bitmap_top;

            // subtle shadow first
            for (unsigned int yy = 0; yy < bm.rows; ++yy)
            {
                for (unsigned int xx = 0; xx < bm.width; ++xx)
                {
                    uint8_t cov = (bm.pixel_mode == FT_PIXEL_MODE_GRAY) ? bm.buffer[int(yy) * bm.pitch + int(xx)] : 0;
                    if (!cov) continue;
                    uint8_t sa = (uint8_t)((int)cov * 90 / 255);
                    blendPixel(rgba, W, H, left + (int)xx + 1, top + (int)yy + 1, 0, 0, 0, sa);
                }
            }

            // glyph
            for (unsigned int yy = 0; yy < bm.rows; ++yy)
            {
                for (unsigned int xx = 0; xx < bm.width; ++xx)
                {
                    uint8_t cov = 0;
                    if (bm.pixel_mode == FT_PIXEL_MODE_GRAY)
                        cov = bm.buffer[int(yy) * bm.pitch + int(xx)];
                    else if (bm.pixel_mode == FT_PIXEL_MODE_MONO)
                    {
                        uint8_t byte = bm.buffer[int(yy) * bm.pitch + int(xx >> 3)];
                        cov = (byte & (0x80u >> (xx & 7u))) ? 255 : 0;
                    }
                    if (!cov) continue;
                    uint8_t fa = (uint8_t)((int)cov * a / 255);
                    blendPixel(rgba, W, H, left + (int)xx, top + (int)yy, r, g, b, fa);
                }
            }

            // extra thickening fallback (cheap overdraw)
            if (!varOk && weight >= 700)
            {
                for (unsigned int yy = 0; yy < bm.rows; ++yy)
                {
                    for (unsigned int xx = 0; xx < bm.width; ++xx)
                    {
                        uint8_t cov = (bm.pixel_mode == FT_PIXEL_MODE_GRAY) ? bm.buffer[int(yy) * bm.pitch + int(xx)] : 0;
                        if (!cov) continue;
                        uint8_t fa = (uint8_t)((int)cov * a / 255);
                        blendPixel(rgba, W, H, left + (int)xx + 1, top + (int)yy, r, g, b, (uint8_t)(fa * 0.65f));
                    }
                }
            }

            penX += (slot->advance.x >> 6);
        }
    }

