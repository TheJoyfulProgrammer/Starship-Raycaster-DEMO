void App::transitionImageLayout(VkCommandBuffer cmd, VkImage image,
                                VkImageLayout oldLayout, VkImageLayout newLayout,
                                VkPipelineStageFlags2 srcStage, VkAccessFlags2 srcAccess,
                                VkPipelineStageFlags2 dstStage, VkAccessFlags2 dstAccess,
                                VkImageAspectFlags aspect)
{
    VkImageMemoryBarrier2 barrier{VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER_2};
    barrier.srcStageMask = srcStage;
    barrier.srcAccessMask = srcAccess;
    barrier.dstStageMask = dstStage;
    barrier.dstAccessMask = dstAccess;
    barrier.oldLayout = oldLayout;
    barrier.newLayout = newLayout;
    barrier.image = image;
    barrier.srcQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
    barrier.dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
    barrier.subresourceRange.aspectMask = aspect;
    barrier.subresourceRange.baseMipLevel = 0;
    barrier.subresourceRange.levelCount = 1;
    barrier.subresourceRange.baseArrayLayer = 0;
    barrier.subresourceRange.layerCount = 1;

    VkDependencyInfo dep{VK_STRUCTURE_TYPE_DEPENDENCY_INFO};
    dep.imageMemoryBarrierCount = 1;
    dep.pImageMemoryBarriers = &barrier;

    vkCmdPipelineBarrier2(cmd, &dep);
}

// -------------------- palette update --------------------

void App::buildPerceptualPaletteFromReadback(const Frame& frame)
{
    if (!frame.readbackMapped || frame.readbackW == 0 || frame.readbackH == 0) return;
    const uint8_t* rgba = reinterpret_cast<const uint8_t*>(frame.readbackMapped);
    perceptualPalette_ = star::pal::buildPerceptualPalette(rgba, (int)frame.readbackW, (int)frame.readbackH);
    perceptualGen_++;
    perceptualReady_ = true;

    // If we're actively using the perceptual preset, apply immediately.
    if (palettePreset_ == star::pal::PalettePreset::Perceptual)
    {
        cpuPalette_ = perceptualPalette_;
        appliedPerceptualGen_ = perceptualGen_;
        paletteDirty_ = false;
        lutDirty_ = true;
    }
}

void App::rebuildLut()
{
    cpuLut_ = star::pal::buildLut33(cpuPalette_, colorsToUse_);
    lutDirty_ = false;
}

void App::writeGpuPalette(uint32_t frameIndex)
{
    // Pack palette as vec4 float (0..1). Stored in dynamic storage buffer at offset.
    const VkDeviceSize ofs = paletteStride_ * frameIndex;
    float* dst = reinterpret_cast<float*>(reinterpret_cast<uint8_t*>(paletteDyn_.mapped) + ofs);

    for (int i=0;i<256;++i)
    {
        dst[i*4+0] = cpuPalette_[i].r / 255.0f;
        dst[i*4+1] = cpuPalette_[i].g / 255.0f;
        dst[i*4+2] = cpuPalette_[i].b / 255.0f;
        dst[i*4+3] = 1.0f;
    }
}

void App::writeGpuLut(uint32_t frameIndex)
{
    if (cpuLut_.empty()) rebuildLut();

    const VkDeviceSize ofs = lutStride_ * frameIndex;
    uint8_t* base = reinterpret_cast<uint8_t*>(lutDyn_.mapped) + ofs;
    std::memcpy(base, cpuLut_.data(), cpuLut_.size() * sizeof(uint32_t));
}

void App::updatePaletteIfNeeded(uint32_t frameIndex)
{
    bool paletteChanged = false;

    // If perceptual palette was rebuilt (from histogram), apply it when perceptual preset is active.
    if (palettePreset_ == star::pal::PalettePreset::Perceptual && perceptualReady_ && appliedPerceptualGen_ != perceptualGen_)
    {
        cpuPalette_ = perceptualPalette_;
        appliedPerceptualGen_ = perceptualGen_;
        paletteDirty_ = false;
        paletteChanged = true;
        lutDirty_ = true;
    }

    // If preset isn't perceptual, rebuild palette immediately on CPU.
    if (paletteDirty_ && palettePreset_ != star::pal::PalettePreset::Perceptual)
    {
        using P = star::pal::PalettePreset;
        switch (palettePreset_)
        {
            case P::Grayscale:  cpuPalette_ = star::pal::buildGradientN({0,0,0}, {255,255,255}, colorsToUse_); break;
            case P::Green33:    cpuPalette_ = star::pal::buildGradientN({0,0,0}, {0x33,0xFF,0x33}, colorsToUse_); break;
            case P::Green66:    cpuPalette_ = star::pal::buildGradientN({0,0,0}, {0x66,0xFF,0x66}, colorsToUse_); break;
            case P::GoldCC:     cpuPalette_ = star::pal::buildGradientN({0,0,0}, {0xFF,0xCC,0x00}, colorsToUse_); break;
            case P::GoldB0:     cpuPalette_ = star::pal::buildGradientN({0,0,0}, {0xFF,0xB0,0x00}, colorsToUse_); break;
            case P::VGA256:     cpuPalette_ = star::pal::buildVga256(); break;
            case P::ColorTheory: cpuPalette_ = star::pal::buildColorTheoryN(ctHue_, ctLuma_, ctScheme_, colorsToUse_); break;
            case P::MutedTeal:  cpuPalette_ = star::pal::buildGradientN({0,0,0}, {0x2F,0x78,0x75}, colorsToUse_); break;
            case P::Vermilion:  cpuPalette_ = star::pal::buildGradientN({0,0,0}, {0xC0,0x4D,0x3E}, colorsToUse_); break;
            default: break;
        }
        paletteDirty_ = false;
        paletteChanged = true;
        lutDirty_ = true;
    }

    if (paletteChanged)
        ++paletteGen_;

    // Palette is always uploaded to the per-frame dynamic region.
    writeGpuPalette(frameIndex);
}

// -------------------- draw frame --------------------


void App::drawFrame()
{
    Frame& frame = frames_[currentFrame_];

    // Hybrid input: SDL events normally, plus keyboard edge polling as a fallback (e.g. during interactive resize).
    const bool allowPolledEdges = (keyEventSerial_ == keyEventSerialSeen_);
    pollKeyboard(allowPolledEdges);
    keyEventSerialSeen_ = keyEventSerial_;

    // Wait for this frame's resources to be free (command buffer + per-frame dynamic slices).
    vkWaitForFences(device_, 1, &frame.inFlightFence, VK_TRUE, UINT64_MAX);

    uint32_t imageIndex = 0;
    VkResult acq = vkAcquireNextImageKHR(device_, swapchain_, UINT64_MAX,
                                        frame.imageAvailableSemaphore, VK_NULL_HANDLE, &imageIndex);
    if (acq == VK_ERROR_OUT_OF_DATE_KHR || framebufferDirty_)
    {
        recreateSwapchain();
        return;
    }
    vkCheck(acq, "vkAcquireNextImageKHR");

    // If this swapchain image is already in flight, wait for its fence.
    if (imagesInFlight_[imageIndex] != VK_NULL_HANDLE)
        vkWaitForFences(device_, 1, &imagesInFlight_[imageIndex], VK_TRUE, UINT64_MAX);
    imagesInFlight_[imageIndex] = frame.inFlightFence;

    // Optional: refresh perceptual palette cache from the GPU histogram of the last time this image was used.
    // (Fence wait above guarantees the histogram write is complete.)
    // Only relevant while palette-index mode is ON.
    const bool wantPerceptualCache = paletteIndexMode_ && (alwaysBuildPerceptual_ || (palettePreset_ == star::pal::PalettePreset::Perceptual));
    if (wantPerceptualCache && imageIndex < histBuffers_.size() && imageIndex < histEverSubmitted_.size() && histEverSubmitted_[imageIndex])
    {
        const uint32_t* hist = reinterpret_cast<const uint32_t*>(histBuffers_[imageIndex].mapped);
        if (hist)
        {
            perceptualPalette_ = star::pal::buildPerceptualPaletteFromHistogram33(hist, colorsToUse_);
            perceptualReady_ = true;
            ++perceptualGen_;
        }
    }

    // Upload palette for this frame slice (and apply perceptual if it just updated).
    if (paletteIndexMode_)
        updatePaletteIfNeeded(currentFrame_);

    // Reset for this submit.
    vkResetFences(device_, 1, &frame.inFlightFence);
    vkResetCommandBuffer(frame.commandBuffer, 0);

    VkCommandBuffer cmd = frame.commandBuffer;
    VkCommandBufferBeginInfo bi{VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO};
    vkCheck(vkBeginCommandBuffer(cmd, &bi), "vkBeginCommandBuffer");

    // Time
    timeSeconds_ = double(SDL_GetTicks()) / 1000.0;

    // Delta time (always available, even when the game layer is OFF).
    if (lastTimeSeconds_ <= 0.0)
        lastTimeSeconds_ = timeSeconds_;
    const double dt = timeSeconds_ - lastTimeSeconds_;
    lastTimeSeconds_ = timeSeconds_;

    // Smooth tactical-map fade.
    {
        const float target = fullMapWanted_ ? 1.0f : 0.0f;
        const float step = (float)dt * 4.0f; // ~250ms-ish in/out
        if (fullMapAlpha_ < target) fullMapAlpha_ = std::min(target, fullMapAlpha_ + step);
        else if (fullMapAlpha_ > target) fullMapAlpha_ = std::max(target, fullMapAlpha_ - step);
    }

    // Smooth full-map zoom/pan (Option B).
    {
        const float k = 1.0f - std::exp(-(float)dt * 12.0f);
        fullMapZoom_ += (fullMapZoomTarget_ - fullMapZoom_) * k;
        fullMapPanXCells_ += (fullMapPanXTargetCells_ - fullMapPanXCells_) * k;
        fullMapPanYCells_ += (fullMapPanYTargetCells_ - fullMapPanYCells_) * k;
        // Clamp zoom sane even if some caller goes wild.
        fullMapZoom_ = std::max(0.25f, std::min(20.0f, fullMapZoom_));
    }

    // Keep HUD health value in lockstep with vignette size.
    syncHealthFromVignette();

    // Mouse capture hint fade.
    {
        const float target = mouseCaptured_ ? 0.0f : 1.0f;
        const float step = (float)dt * (mouseCaptured_ ? 6.0f : 3.0f);
        if (mouseHintAlpha_ < target) mouseHintAlpha_ = std::min(target, mouseHintAlpha_ + step);
        else if (mouseHintAlpha_ > target) mouseHintAlpha_ = std::max(target, mouseHintAlpha_ - step);
    }

    // Game update (CPU simulation) + SSBO upload (per frame slot)
    if (gameEnabled_)
    {
        updateGame(dt);
        uploadGameMap(currentFrame_);
        uploadSprites(currentFrame_);
    }

    // --- Ensure index image is GENERAL for storage writes ---
    if (paletteIndexMode_)
    {
        VkImageLayout old = indexLayout_[imageIndex];
        if (old != VK_IMAGE_LAYOUT_GENERAL)
        {
            VkPipelineStageFlags2 srcStage = VK_PIPELINE_STAGE_2_TOP_OF_PIPE_BIT;
            VkAccessFlags2 srcAccess = 0;
            if (old == VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL) { srcStage = VK_PIPELINE_STAGE_2_FRAGMENT_SHADER_BIT; srcAccess = VK_ACCESS_2_SHADER_SAMPLED_READ_BIT; }
            else if (old == VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL) { srcStage = VK_PIPELINE_STAGE_2_TRANSFER_BIT; srcAccess = VK_ACCESS_2_TRANSFER_WRITE_BIT; }
            else if (old == VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL) { srcStage = VK_PIPELINE_STAGE_2_TRANSFER_BIT; srcAccess = VK_ACCESS_2_TRANSFER_READ_BIT; }

            transitionImageLayout(cmd, indexImage_[imageIndex].image,
                                  old, VK_IMAGE_LAYOUT_GENERAL,
                                  srcStage, srcAccess,
                                  VK_PIPELINE_STAGE_2_COMPUTE_SHADER_BIT, VK_ACCESS_2_SHADER_STORAGE_WRITE_BIT);
            indexLayout_[imageIndex] = VK_IMAGE_LAYOUT_GENERAL;
        }
    }

    // --- Offscreen render (effect) ---
    {
        VkImageLayout old = offscreenLayout_[imageIndex];

        VkPipelineStageFlags2 srcStage = VK_PIPELINE_STAGE_2_TOP_OF_PIPE_BIT;
        VkAccessFlags2 srcAccess = 0;
        if (old == VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL) { srcStage = VK_PIPELINE_STAGE_2_COMPUTE_SHADER_BIT; srcAccess = VK_ACCESS_2_SHADER_SAMPLED_READ_BIT; }
        else if (old == VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL) { srcStage = VK_PIPELINE_STAGE_2_TRANSFER_BIT; srcAccess = VK_ACCESS_2_TRANSFER_READ_BIT; }
        else if (old == VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL) { srcStage = VK_PIPELINE_STAGE_2_TRANSFER_BIT; srcAccess = VK_ACCESS_2_TRANSFER_WRITE_BIT; }
        else if (old == VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL) { srcStage = VK_PIPELINE_STAGE_2_COLOR_ATTACHMENT_OUTPUT_BIT; srcAccess = VK_ACCESS_2_COLOR_ATTACHMENT_WRITE_BIT; }

        transitionImageLayout(cmd, offscreen_[imageIndex].image,
                              old, VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL,
                              srcStage, srcAccess,
                              VK_PIPELINE_STAGE_2_COLOR_ATTACHMENT_OUTPUT_BIT, VK_ACCESS_2_COLOR_ATTACHMENT_WRITE_BIT);

        offscreenLayout_[imageIndex] = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;

        VkRenderingAttachmentInfo colorAtt{VK_STRUCTURE_TYPE_RENDERING_ATTACHMENT_INFO};
        colorAtt.imageView = offscreen_[imageIndex].view;
        colorAtt.imageLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
        colorAtt.loadOp = VK_ATTACHMENT_LOAD_OP_CLEAR;
        colorAtt.storeOp = VK_ATTACHMENT_STORE_OP_STORE;
        VkClearValue clear{};
        clear.color.float32[0] = 0.0f;
        clear.color.float32[1] = 0.0f;
        clear.color.float32[2] = 0.0f;
        clear.color.float32[3] = 1.0f;
        colorAtt.clearValue = clear;

        VkExtent2D re = offscreen_[imageIndex].extent;

        VkRenderingInfo ri{VK_STRUCTURE_TYPE_RENDERING_INFO};
        ri.renderArea.extent = re;
        ri.layerCount = 1;
        ri.colorAttachmentCount = 1;
        ri.pColorAttachments = &colorAtt;

        vkCmdBeginRendering(cmd, &ri);

        VkViewport vp{};
        vp.width  = (float)re.width;
        vp.height = (float)re.height;
        vp.minDepth = 0.0f;
        vp.maxDepth = 1.0f;

        VkRect2D sc{};
        sc.extent = re;

        vkCmdSetViewport(cmd, 0, 1, &vp);
        vkCmdSetScissor(cmd, 0, 1, &sc);

        if (!effects_.empty())
        {
            vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, effects_[activeEffect_].pipeline);

            // push constant: rt + camera (player) info.
            // Existing effect shaders only read the first vec4; the skybox variant also reads camera.
            float pc[8] = {
                (float)re.width, (float)re.height, (float)timeSeconds_, 0.0f,
                playerX_, playerY_, playerAngle_, 0.0f
            };
            vkCmdPushConstants(cmd, effectPipelineLayout_, VK_SHADER_STAGE_FRAGMENT_BIT, 0, sizeof(pc), pc);

            vkCmdDraw(cmd, 3, 1, 0, 0);
        }

        // --- Game overlay (raycaster) ---
        if (gameEnabled_ && gamePipeline_ != VK_NULL_HANDLE)
        {
            vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, gamePipeline_);
            VkDescriptorSet gds = gameDescSets_[currentFrame_];
            vkCmdBindDescriptorSets(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, gamePipelineLayout_,
                                    0, 1, &gds, 0, nullptr);

            struct GamePC { float a[4]; float b[4]; float c[4]; uint32_t d[4]; } pc{};
            pc.a[0] = (float)re.width;
            pc.a[1] = (float)re.height;
            pc.a[2] = (float)timeSeconds_;
            pc.a[3] = std::max(0.0f, std::min(1.0f, gameAlpha_));

            pc.b[0] = playerX_;
            pc.b[1] = playerY_;
            pc.b[2] = playerAngle_;
            // pc.b.w is used by the raycaster shader as a vertical pitch (in pixels).
            const float halfPi = 1.5707963267948966192f;
            float pitchNorm = (halfPi > 0.0f) ? (playerPitchAngle_ / halfPi) : 0.0f;
            pitchNorm = std::max(-1.0f, std::min(1.0f, pitchNorm));
            pc.b[3] = pitchNorm * (0.5f * (float)re.height);
            pc.c[0] = playerEyeZ_;
            pc.c[1] = (float)spriteCount_;
            // Limit maxHits a bit by default to keep GPU cost predictable on large maps.
            pc.c[2] = 4.0f; // maxHits for multi-hit transparency
            pc.c[3] = 0.0f;

            pc.d[0] = mapW_;
            pc.d[1] = mapH_;
            pc.d[2] = 0u;
            pc.d[3] = 0u;

            vkCmdPushConstants(cmd, gamePipelineLayout_, VK_SHADER_STAGE_FRAGMENT_BIT, 0, sizeof(pc), &pc);
            vkCmdDraw(cmd, 3, 1, 0, 0);
        }



        // --- Health vignette overlay (3rd layer) ---
        struct OverlayPC { float a[4]; float b[4]; float c[4]; uint32_t d[4]; };

        if (healthVignetteEnabled_ && healthPipeline_ != VK_NULL_HANDLE)
        {
            vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, healthPipeline_);

            float maxSize = 0.5f * (float)std::min(re.width, re.height);
            float baseSize = std::max(0.0f, std::min(maxSize, healthVignetteSizePx_));

            OverlayPC pc{};
            pc.a[0] = (float)re.width;
            pc.a[1] = (float)re.height;
            pc.a[2] = (float)timeSeconds_;
            pc.a[3] = 1.0f;
            pc.b[0] = baseSize;
            pc.b[1] = std::max(0.0f, std::min(1.0f, (float)hudHealth_ / 100.0f));

            vkCmdPushConstants(cmd, healthPipelineLayout_, VK_SHADER_STAGE_FRAGMENT_BIT, 0, sizeof(pc), &pc);
            vkCmdDraw(cmd, 3, 1, 0, 0);
        }
        vkCmdEndRendering(cmd);

    // Make the offscreen color available to compute/fragment sampling.
        transitionImageLayout(cmd, offscreen_[imageIndex].image,
                              VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL,
                              VK_PIPELINE_STAGE_2_COLOR_ATTACHMENT_OUTPUT_BIT, VK_ACCESS_2_COLOR_ATTACHMENT_WRITE_BIT,
                              VK_PIPELINE_STAGE_2_COMPUTE_SHADER_BIT | VK_PIPELINE_STAGE_2_FRAGMENT_SHADER_BIT,
                              VK_ACCESS_2_SHADER_SAMPLED_READ_BIT);
        offscreenLayout_[imageIndex] = VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL;
    }

    // Dynamic offsets (palette + LUT slices for this frame index).
    uint32_t dynOffsets[2] = {
        (uint32_t)(paletteStride_ * currentFrame_),
        (uint32_t)(lutStride_ * currentFrame_)
    };

    // --- Histogram compute (writes histBuffers_[imageIndex]) ---
    if (paletteIndexMode_ && imageIndex < histBuffers_.size())
    {
        // Clear histogram first.
        vkCmdFillBuffer(cmd, histBuffers_[imageIndex].buffer, 0, histBuffers_[imageIndex].size, 0);

        VkBufferMemoryBarrier2 fillToCompute{VK_STRUCTURE_TYPE_BUFFER_MEMORY_BARRIER_2};
        fillToCompute.srcStageMask = VK_PIPELINE_STAGE_2_TRANSFER_BIT;
        fillToCompute.srcAccessMask = VK_ACCESS_2_TRANSFER_WRITE_BIT;
        fillToCompute.dstStageMask = VK_PIPELINE_STAGE_2_COMPUTE_SHADER_BIT;
        fillToCompute.dstAccessMask = VK_ACCESS_2_SHADER_READ_BIT | VK_ACCESS_2_SHADER_WRITE_BIT;
        fillToCompute.buffer = histBuffers_[imageIndex].buffer;
        fillToCompute.offset = 0;
        fillToCompute.size = histBuffers_[imageIndex].size;

        VkDependencyInfo dep{VK_STRUCTURE_TYPE_DEPENDENCY_INFO};
        dep.bufferMemoryBarrierCount = 1;
        dep.pBufferMemoryBarriers = &fillToCompute;
        vkCmdPipelineBarrier2(cmd, &dep);

        vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_COMPUTE, histogramPipeline_);
        vkCmdBindDescriptorSets(cmd, VK_PIPELINE_BIND_POINT_COMPUTE, histogramPipelineLayout_,
                                0, 1, &descSets_[imageIndex], 2, dynOffsets);

        struct HistPC { uint32_t srcW, srcH, gridW, gridH; } pc{};
        pc.srcW = offscreen_[imageIndex].extent.width;
        pc.srcH = offscreen_[imageIndex].extent.height;
        pc.gridW = std::min(320u, pc.srcW);
        pc.gridH = std::min(180u, pc.srcH);

        vkCmdPushConstants(cmd, histogramPipelineLayout_, VK_SHADER_STAGE_COMPUTE_BIT, 0, sizeof(pc), &pc);

        const uint32_t gx = (pc.gridW + 7u) / 8u;
        const uint32_t gy = (pc.gridH + 7u) / 8u;
        vkCmdDispatch(cmd, gx, gy, 1);
    }
    // --- LUT build compute (writes lutDyn slice for this frame) ---
    if (paletteIndexMode_)
    {
        const bool needLut = (lutBuiltGen_[currentFrame_] != paletteGen_) || (lutBuiltColors_[currentFrame_] != colorsToUse_);

        if (needLut)
        {
            vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_COMPUTE, lutBuildPipeline_);
            vkCmdBindDescriptorSets(cmd, VK_PIPELINE_BIND_POINT_COMPUTE, lutBuildPipelineLayout_,
                                    0, 1, &descSets_[imageIndex], 2, dynOffsets);

            struct LutPC { uint32_t colorsToUse, pad1, pad2, pad3; } pc{};
            pc.colorsToUse = colorsToUse_;

            vkCmdPushConstants(cmd, lutBuildPipelineLayout_, VK_SHADER_STAGE_COMPUTE_BIT, 0, sizeof(pc), &pc);

            const uint32_t total = 33u * 33u * 33u;
            const uint32_t gx = (total + 255u) / 256u;
            vkCmdDispatch(cmd, gx, 1, 1);

            // Update per-frame-slot cache tags.
            lutBuiltGen_[currentFrame_] = paletteGen_;
            lutBuiltColors_[currentFrame_] = colorsToUse_;
        }

        // Make LUT writes (from this frame, or from a previous use of this frame slot) visible to quantize compute.
        VkBufferMemoryBarrier2 lutBarrier{VK_STRUCTURE_TYPE_BUFFER_MEMORY_BARRIER_2};
        lutBarrier.srcStageMask = VK_PIPELINE_STAGE_2_COMPUTE_SHADER_BIT;
        lutBarrier.srcAccessMask = VK_ACCESS_2_SHADER_WRITE_BIT;
        lutBarrier.dstStageMask = VK_PIPELINE_STAGE_2_COMPUTE_SHADER_BIT;
        lutBarrier.dstAccessMask = VK_ACCESS_2_SHADER_READ_BIT;
        lutBarrier.buffer = lutDyn_.buffer;
        lutBarrier.offset = lutStride_ * currentFrame_;
        lutBarrier.size = lutStride_;

        VkDependencyInfo dep{VK_STRUCTURE_TYPE_DEPENDENCY_INFO};
        dep.bufferMemoryBarrierCount = 1;
        dep.pBufferMemoryBarriers = &lutBarrier;
        vkCmdPipelineBarrier2(cmd, &dep);
    }

    // --- Quantize compute (writes index image) ---
    if (paletteIndexMode_)
    {
        vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_COMPUTE, quantizePipeline_);
        vkCmdBindDescriptorSets(cmd, VK_PIPELINE_BIND_POINT_COMPUTE, quantizePipelineLayout_,
                                0, 1, &descSets_[imageIndex], 2, dynOffsets);

        struct QuantPC
        {
            uint32_t width, height, colorsToUse, ditherMode, frameIndex;
            float ditherStrength;
            uint32_t pad0, pad1;
        } pc{};
        pc.width = indexImage_[imageIndex].extent.width;
        pc.height = indexImage_[imageIndex].extent.height;
        pc.colorsToUse = colorsToUse_;
        pc.ditherMode = ditheringEnabled_ ? (uint32_t)ditherMode_ : 0u;

        uint32_t fi = (uint32_t)frameCounter_;
        if (pc.ditherMode == (uint32_t)star::pal::DitherMode::BlueNoise)
        {
            if (!bnDriftEnabled_) fi = 0u;
            else if (bnDriftDiv_ > 1u) fi = (uint32_t)(frameCounter_ / (uint64_t)bnDriftDiv_);
        }
        pc.frameIndex = fi;

        pc.ditherStrength = ditheringEnabled_ ? ditherStrength_ : 0.0f;

        vkCmdPushConstants(cmd, quantizePipelineLayout_, VK_SHADER_STAGE_COMPUTE_BIT, 0, sizeof(pc), &pc);

		const bool slow = (pc.ditherMode == 1u || pc.ditherMode == 2u || pc.ditherMode == 4u || pc.ditherMode == 5u || pc.ditherMode == 6u || pc.ditherMode == 8u);
        if (slow)
        {
            vkCmdDispatch(cmd, 1, 1, 1);
        }
        else
        {
            uint32_t gx = (swapchainExtent_.width + 15) / 16;
            uint32_t gy = (swapchainExtent_.height + 15) / 16;
            vkCmdDispatch(cmd, gx, gy, 1);
        }

        // Barrier: compute write -> fragment read (index image sampled in display pass)
        VkImageMemoryBarrier2 b{VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER_2};
        b.srcStageMask = VK_PIPELINE_STAGE_2_COMPUTE_SHADER_BIT;
        b.srcAccessMask = VK_ACCESS_2_SHADER_STORAGE_WRITE_BIT;
        b.dstStageMask = VK_PIPELINE_STAGE_2_FRAGMENT_SHADER_BIT;
        b.dstAccessMask = VK_ACCESS_2_SHADER_SAMPLED_READ_BIT;
        b.oldLayout = VK_IMAGE_LAYOUT_GENERAL;
        b.newLayout = VK_IMAGE_LAYOUT_GENERAL;
        b.image = indexImage_[imageIndex].image;
        b.srcQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
        b.dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
        b.subresourceRange = fullColorRange();

        VkDependencyInfo dep{VK_STRUCTURE_TYPE_DEPENDENCY_INFO};
        dep.imageMemoryBarrierCount = 1;
        dep.pImageMemoryBarriers = &b;
        vkCmdPipelineBarrier2(cmd, &dep);
    }

    // --- Composite pass (Display -> composite + GUI) ---
    {
        // Transition composite image to COLOR_ATTACHMENT
        VkImageLayout old = compositeLayout_[imageIndex];
        VkPipelineStageFlags2 srcStage = VK_PIPELINE_STAGE_2_TOP_OF_PIPE_BIT;
        VkAccessFlags2 srcAccess = 0;

        if (old == VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL)
        {
            srcStage = VK_PIPELINE_STAGE_2_FRAGMENT_SHADER_BIT;
            srcAccess = VK_ACCESS_2_SHADER_SAMPLED_READ_BIT;
        }
        else if (old == VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL)
        {
            srcStage = VK_PIPELINE_STAGE_2_COLOR_ATTACHMENT_OUTPUT_BIT;
            srcAccess = VK_ACCESS_2_COLOR_ATTACHMENT_WRITE_BIT;
        }

        transitionImageLayout(cmd, composite_[imageIndex].image,
                              old, VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL,
                              srcStage, srcAccess,
                              VK_PIPELINE_STAGE_2_COLOR_ATTACHMENT_OUTPUT_BIT, VK_ACCESS_2_COLOR_ATTACHMENT_WRITE_BIT);
        compositeLayout_[imageIndex] = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;

        VkRenderingAttachmentInfo colorAtt{VK_STRUCTURE_TYPE_RENDERING_ATTACHMENT_INFO};
        colorAtt.imageView = composite_[imageIndex].view;
        colorAtt.imageLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
        colorAtt.loadOp = VK_ATTACHMENT_LOAD_OP_CLEAR;
        colorAtt.storeOp = VK_ATTACHMENT_STORE_OP_STORE;
        VkClearValue clear{};
        clear.color.float32[0] = 0.0f;
        clear.color.float32[1] = 0.0f;
        clear.color.float32[2] = 0.0f;
        clear.color.float32[3] = 1.0f;
        colorAtt.clearValue = clear;

        VkRenderingInfo ri{VK_STRUCTURE_TYPE_RENDERING_INFO};
        ri.renderArea.extent = swapchainExtent_;
        ri.layerCount = 1;
        ri.colorAttachmentCount = 1;
        ri.pColorAttachments = &colorAtt;

        vkCmdBeginRendering(cmd, &ri);

        VkViewport vp{};
        vp.width  = (float)swapchainExtent_.width;
        vp.height = (float)swapchainExtent_.height;
        vp.minDepth = 0.0f;
        vp.maxDepth = 1.0f;

        VkRect2D sc{};
        sc.extent = swapchainExtent_;

        vkCmdSetViewport(cmd, 0, 1, &vp);
        vkCmdSetScissor(cmd, 0, 1, &sc);

        // First: display the pixelated/indexed world into composite_
        vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, paletteIndexMode_ ? displayPipeline_ : fullcolorPipeline_);

        // dynamic offsets: palette, LUT (LUT offset still required by set layout even if display shader doesn't use it)
        vkCmdBindDescriptorSets(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, displayPipelineLayout_,
                                0, 1, &descSets_[imageIndex], 2, dynOffsets);

        struct DisplayPC { uint32_t pixelSize, pad0, pad1, pad2; } dpc{pixelSize_, 0u, 0u, 0u};
        vkCmdPushConstants(cmd, displayPipelineLayout_, VK_SHADER_STAGE_FRAGMENT_BIT, 0, sizeof(dpc), &dpc);

        vkCmdDraw(cmd, 3, 1, 0, 0);

        // Then: draw GUI into composite at full resolution (stays crisp, *then* CRT warps it in present pass)
        if (guiEnabled_ && guiPipeline_ != VK_NULL_HANDLE)
        {
            vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, guiPipeline_);

            VkDescriptorSet uds = guiDescSets_[currentFrame_];
            vkCmdBindDescriptorSets(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, guiPipelineLayout_,
                                    0, 1, &uds, 0, nullptr);

            struct GuiPC { float a[4]; float b[4]; float c[4]; uint32_t d[4]; float e[4]; } pc{};
            pc.a[0] = (float)swapchainExtent_.width;
            pc.a[1] = (float)swapchainExtent_.height;
            pc.a[2] = (float)timeSeconds_;
            pc.a[3] = 1.0f;

            pc.b[0] = playerX_;
            pc.b[1] = playerY_;
            pc.b[2] = playerAngle_;
            pc.b[3] = (float)minimapPos_;

            pc.c[0] = (float)hudHealth_;
            pc.c[1] = (float)hudAmmo_;
            pc.c[2] = (float)minimapSizePx_;
            pc.c[3] = fullMapAlpha_;

            pc.d[0] = mapW_;
            pc.d[1] = mapH_;
            pc.d[2] = mapCrtMode_;
            {
                uint32_t hint8 = (uint32_t)std::max(0, std::min(255, (int)std::lround(mouseHintAlpha_ * 255.0f)));
                pc.d[3] = (mapCrtAffectsLegend_ ? 1u : 0u) | (mouseCaptured_ ? 2u : 0u) | (hint8 << 8);
            }

            // Full-map pan (in cells) + zoom multiplier for Option B.
            pc.e[0] = fullMapPanXCells_;
            pc.e[1] = fullMapPanYCells_;
            pc.e[2] = fullMapZoom_;
            pc.e[3] = 0.0f;

            vkCmdPushConstants(cmd, guiPipelineLayout_, VK_SHADER_STAGE_FRAGMENT_BIT, 0, sizeof(pc), &pc);
            vkCmdDraw(cmd, 3, 1, 0, 0);
        }

        vkCmdEndRendering(cmd);

        // Transition composite to SHADER_READ_ONLY for the present pass
        transitionImageLayout(cmd, composite_[imageIndex].image,
                              VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL,
                              VK_PIPELINE_STAGE_2_COLOR_ATTACHMENT_OUTPUT_BIT, VK_ACCESS_2_COLOR_ATTACHMENT_WRITE_BIT,
                              VK_PIPELINE_STAGE_2_FRAGMENT_SHADER_BIT, VK_ACCESS_2_SHADER_SAMPLED_READ_BIT);
        compositeLayout_[imageIndex] = VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL;
    }

    // --- Present pass (CRT -> swapchain) ---
    {
        VkImageLayout old = swapchainLayouts_[imageIndex];
        VkPipelineStageFlags2 srcStage = VK_PIPELINE_STAGE_2_TOP_OF_PIPE_BIT;
        VkAccessFlags2 srcAccess = 0;
        if (old == VK_IMAGE_LAYOUT_PRESENT_SRC_KHR) { srcStage = VK_PIPELINE_STAGE_2_NONE; srcAccess = 0; }
        else if (old == VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL) { srcStage = VK_PIPELINE_STAGE_2_COLOR_ATTACHMENT_OUTPUT_BIT; srcAccess = VK_ACCESS_2_COLOR_ATTACHMENT_WRITE_BIT; }

        transitionImageLayout(cmd, swapchainImages_[imageIndex],
                              old, VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL,
                              srcStage, srcAccess,
                              VK_PIPELINE_STAGE_2_COLOR_ATTACHMENT_OUTPUT_BIT, VK_ACCESS_2_COLOR_ATTACHMENT_WRITE_BIT);
        swapchainLayouts_[imageIndex] = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;

        VkRenderingAttachmentInfo colorAtt{VK_STRUCTURE_TYPE_RENDERING_ATTACHMENT_INFO};
        colorAtt.imageView = swapchainImageViews_[imageIndex];
        colorAtt.imageLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
        colorAtt.loadOp = VK_ATTACHMENT_LOAD_OP_CLEAR;
        colorAtt.storeOp = VK_ATTACHMENT_STORE_OP_STORE;
        VkClearValue clear{};
        clear.color.float32[0] = 0.0f;
        clear.color.float32[1] = 0.0f;
        clear.color.float32[2] = 0.0f;
        clear.color.float32[3] = 1.0f;
        colorAtt.clearValue = clear;

        VkRenderingInfo ri{VK_STRUCTURE_TYPE_RENDERING_INFO};
        ri.renderArea.extent = swapchainExtent_;
        ri.layerCount = 1;
        ri.colorAttachmentCount = 1;
        ri.pColorAttachments = &colorAtt;

        vkCmdBeginRendering(cmd, &ri);

        VkViewport vp{};
        vp.width  = (float)swapchainExtent_.width;
        vp.height = (float)swapchainExtent_.height;
        vp.minDepth = 0.0f;
        vp.maxDepth = 1.0f;

        VkRect2D sc{};
        sc.extent = swapchainExtent_;

        vkCmdSetViewport(cmd, 0, 1, &vp);
        vkCmdSetScissor(cmd, 0, 1, &sc);

        vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, presentPipeline_);
        vkCmdBindDescriptorSets(cmd, VK_PIPELINE_BIND_POINT_GRAPHICS, presentPipelineLayout_,
                                0, 1, &presentDescSets_[imageIndex], 0, nullptr);

        struct PresentPC { float rtW, rtH, time; uint32_t mode; } ppc{};
        ppc.rtW = (float)swapchainExtent_.width;
        ppc.rtH = (float)swapchainExtent_.height;
        ppc.time = (float)timeSeconds_;
        ppc.mode = mapCrtMode_;

        vkCmdPushConstants(cmd, presentPipelineLayout_, VK_SHADER_STAGE_FRAGMENT_BIT, 0, sizeof(ppc), &ppc);
        vkCmdDraw(cmd, 3, 1, 0, 0);

        vkCmdEndRendering(cmd);

        // transition swapchain image to present
        transitionImageLayout(cmd, swapchainImages_[imageIndex],
                              VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL, VK_IMAGE_LAYOUT_PRESENT_SRC_KHR,
                              VK_PIPELINE_STAGE_2_COLOR_ATTACHMENT_OUTPUT_BIT, VK_ACCESS_2_COLOR_ATTACHMENT_WRITE_BIT,
                              VK_PIPELINE_STAGE_2_NONE, 0);
        swapchainLayouts_[imageIndex] = VK_IMAGE_LAYOUT_PRESENT_SRC_KHR;
    }

    vkCheck(vkEndCommandBuffer(cmd), "vkEndCommandBuffer");

    // Submit
    VkSemaphore waitSem = frame.imageAvailableSemaphore;
    VkSemaphore signalSem = frame.renderFinishedSemaphore;

    VkPipelineStageFlags waitStage = VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT;

    VkSubmitInfo si{VK_STRUCTURE_TYPE_SUBMIT_INFO};
    si.waitSemaphoreCount = 1;
    si.pWaitSemaphores = &waitSem;
    si.pWaitDstStageMask = &waitStage;
    si.commandBufferCount = 1;
    si.pCommandBuffers = &cmd;
    si.signalSemaphoreCount = 1;
    si.pSignalSemaphores = &signalSem;

    vkCheck(vkQueueSubmit(graphicsQueue_, 1, &si, frame.inFlightFence), "vkQueueSubmit");

    // Histogram will be valid for this swapchain image once this fence signals.
    if (paletteIndexMode_ && imageIndex < histEverSubmitted_.size())
        histEverSubmitted_[imageIndex] = 1;

    VkPresentInfoKHR pi{VK_STRUCTURE_TYPE_PRESENT_INFO_KHR};
    pi.waitSemaphoreCount = 1;
    pi.pWaitSemaphores = &signalSem;
    pi.swapchainCount = 1;
    pi.pSwapchains = &swapchain_;
    pi.pImageIndices = &imageIndex;

    VkResult pres = vkQueuePresentKHR(presentQueue_, &pi);
    if (pres == VK_ERROR_OUT_OF_DATE_KHR || pres == VK_SUBOPTIMAL_KHR || framebufferDirty_)
    {
        recreateSwapchain();
    }
    else
    {
        vkCheck(pres, "vkQueuePresentKHR");
    }

    currentFrame_ = (currentFrame_ + 1) % MAX_FRAMES_IN_FLIGHT;
    frameCounter_++;
}