    inline void drawHeartIcon(std::vector<uint8_t>& rgba, int W, int H, int x0, int y0, int tile, uint8_t r, uint8_t g, uint8_t b)
    {
        // Simple heart using two circles + triangle-ish bottom.
        const float cx1 = x0 + tile * 0.28f;
        const float cx2 = x0 + tile * 0.73f;
        const float cy  = y0 + tile * 0.40f;
        const float rad = tile * 0.29f;

        for (int y = 0; y < tile; ++y)
        {
            for (int x = 0; x < tile; ++x)
            {
                float fx = x0 + x + 0.5f;
                float fy = y0 + y + 0.5f;

                float dx1 = fx - cx1, dy1 = fy - cy;
                float dx2 = fx - cx2, dy2 = fy - cy;
                bool top = (dx1*dx1 + dy1*dy1) <= rad*rad || (dx2*dx2 + dy2*dy2) <= rad*rad;

                // bottom: inverted triangle region
                float tx = (fx - (x0 + tile * 0.5f)) / (tile * 0.5f);
                float ty = (fy - (y0 + tile * 0.45f)) / (tile * 0.55f);
                bool bot = (ty >= 0.0f) and (ty <= 1.0f) and (abs(tx) <= (1.0f - ty));

                if (top || bot)
                    putPixel(rgba, W, H, x0 + x, y0 + y, r, g, b, 255);
            }
        }
    }

    inline void drawBulletIcon(std::vector<uint8_t>& rgba, int W, int H, int x0, int y0, int tile, uint8_t r, uint8_t g, uint8_t b)
    {
        // Capsule bullet.
        int left   = x0 + int(tile * 0.25f);
        int right  = x0 + int(tile * 0.75f);
        int top    = y0 + int(tile * 0.18f);
        int bottom = y0 + int(tile * 0.82f);
        float cx = (left + right) * 0.5f;
        float rad = (right - left) * 0.5f;

        for (int y = top; y <= bottom; ++y)
        {
            for (int x = left; x <= right; ++x)
            {
                float fx = x + 0.5f;
                float fy = y + 0.5f;

                // top hemisphere + body
                bool inBody = (fy >= top + rad) && (fy <= bottom);
                float dx = fx - cx;
                float dy = fy - (top + rad);
                bool inTop = (dx*dx + dy*dy) <= rad*rad && fy <= top + rad;

                if (inBody || inTop)
                    putPixel(rgba, W, H, x, y, r, g, b, 255);
            }
        }

        // highlight stripe
        for (int y = top + int(rad * 0.6f); y < bottom - int(rad * 0.2f); ++y)
            putPixel(rgba, W, H, left + int(rad * 0.35f), y, 255, 255, 255, 180);
    }
