                float base = 0.44f;
                if ((x % 64) < 2 || (y % 64) < 2) base -= 0.10f;
                if (y == (TILE / 2) || y == (TILE / 2 + 1)) base -= 0.15f; // divider
                base = std::min(1.0f, std::max(0.0f, base));
                r = uint8_t((base * 0.92f) * 255.0f);
                g = uint8_t((base * 0.95f) * 255.0f);
                b = uint8_t((base * 1.00f) * 255.0f);
