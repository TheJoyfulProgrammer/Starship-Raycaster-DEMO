void App::createGuiResources()
{
    if (hudAtlas_.image != VK_NULL_HANDLE && legendAtlas_.image != VK_NULL_HANDLE) return;
    if (hudAtlas_.image != VK_NULL_HANDLE || legendAtlas_.image != VK_NULL_HANDLE) destroyGuiResources();

    constexpr int TILE = 32;
    constexpr int GRID = 16;
    constexpr int W = TILE * GRID;
    constexpr int H = TILE * GRID;

    // Build HUD atlas (digits + icons)
    std::vector<uint8_t> hudRGBA(size_t(W * H * 4), 0);
    if (!blitDigitsFromFreeType(hudRGBA, W, H, TILE, GRID, "fonts/Oxanium-VariableFont_wght.ttf"))
        throw std::runtime_error("FreeType: failed to render digits from fonts/Oxanium-VariableFont_wght.ttf");
    drawHeartIcon(hudRGBA, W, H, 14 * TILE, 0 * TILE, TILE, 220, 40, 40);
    drawBulletIcon(hudRGBA, W, H, 15 * TILE, 0 * TILE, TILE, 235, 215, 120);

    // Build legend atlas (panel + hint)
    std::vector<uint8_t> legendRGBA = buildLegendAtlas512("fonts/Oxanium-VariableFont_wght.ttf");
    if (legendRGBA.empty())
        throw std::runtime_error("FreeType: failed to build legend atlas from fonts/Oxanium-VariableFont_wght.ttf");

    auto createAndUpload = [&](ImageRes& img, VkSampler& samp, const std::vector<uint8_t>& rgba, const char* label)
    {
        img.format = VK_FORMAT_R8G8B8A8_UNORM;
        img.extent = VkExtent2D{ (uint32_t)W, (uint32_t)H };

        createImage((uint32_t)W, (uint32_t)H, img.format, VK_IMAGE_TILING_OPTIMAL,
                    VK_IMAGE_USAGE_SAMPLED_BIT | VK_IMAGE_USAGE_TRANSFER_DST_BIT,
                    VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT,
                    img.image, img.memory);
        img.view = createImageView(img.image, img.format, VK_IMAGE_ASPECT_COLOR_BIT);

        if (samp == VK_NULL_HANDLE)
        {
            VkSamplerCreateInfo sci{VK_STRUCTURE_TYPE_SAMPLER_CREATE_INFO};
            sci.magFilter = VK_FILTER_NEAREST;
            sci.minFilter = VK_FILTER_NEAREST;
            sci.mipmapMode = VK_SAMPLER_MIPMAP_MODE_NEAREST;
            sci.addressModeU = VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE;
            sci.addressModeV = VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE;
            sci.addressModeW = VK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE;
            sci.maxAnisotropy = 1.0f;
            vkCheck(vkCreateSampler(device_, &sci, nullptr, &samp), (std::string("vkCreateSampler(") + label + ")").c_str());
        }

        VkBuffer staging = VK_NULL_HANDLE;
        VkDeviceMemory stagingMem = VK_NULL_HANDLE;
        void* mapped = nullptr;
        VkDeviceSize bytes = VkDeviceSize(rgba.size());

        createBuffer(bytes, VK_BUFFER_USAGE_TRANSFER_SRC_BIT,
                     VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT,
                     staging, stagingMem, &mapped);

        std::memcpy(mapped, rgba.data(), (size_t)bytes);
        vkUnmapMemory(device_, stagingMem);

        VkCommandBufferAllocateInfo ai{VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO};
        ai.commandPool = commandPool_;
        ai.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY;
        ai.commandBufferCount = 1;
        VkCommandBuffer cmd = VK_NULL_HANDLE;
        vkCheck(vkAllocateCommandBuffers(device_, &ai, &cmd), (std::string("vkAllocateCommandBuffers(") + label + ")").c_str());

        VkCommandBufferBeginInfo bi{VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO};
        bi.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
        vkCheck(vkBeginCommandBuffer(cmd, &bi), (std::string("vkBeginCommandBuffer(") + label + ")").c_str());

        transitionImageLayout(cmd, img.image,
                              VK_IMAGE_LAYOUT_UNDEFINED, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL,
                              VK_PIPELINE_STAGE_2_TOP_OF_PIPE_BIT, 0,
                              VK_PIPELINE_STAGE_2_TRANSFER_BIT, VK_ACCESS_2_TRANSFER_WRITE_BIT);

        VkBufferImageCopy region{};
        region.imageSubresource.aspectMask = VK_IMAGE_ASPECT_COLOR_BIT;
        region.imageSubresource.mipLevel = 0;
        region.imageSubresource.baseArrayLayer = 0;
        region.imageSubresource.layerCount = 1;
        region.imageExtent = VkExtent3D{ (uint32_t)W, (uint32_t)H, 1 };
        vkCmdCopyBufferToImage(cmd, staging, img.image, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, 1, &region);

        transitionImageLayout(cmd, img.image,
                              VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL,
                              VK_PIPELINE_STAGE_2_TRANSFER_BIT, VK_ACCESS_2_TRANSFER_WRITE_BIT,
                              VK_PIPELINE_STAGE_2_FRAGMENT_SHADER_BIT, VK_ACCESS_2_SHADER_SAMPLED_READ_BIT);

        vkCheck(vkEndCommandBuffer(cmd), (std::string("vkEndCommandBuffer(") + label + ")").c_str());

        VkSubmitInfo si{VK_STRUCTURE_TYPE_SUBMIT_INFO};
        si.commandBufferCount = 1;
        si.pCommandBuffers = &cmd;
        vkCheck(vkQueueSubmit(graphicsQueue_, 1, &si, VK_NULL_HANDLE), (std::string("vkQueueSubmit(") + label + ")").c_str());
        vkCheck(vkQueueWaitIdle(graphicsQueue_), "vkQueueWaitIdle(guiAtlas)");

        vkFreeCommandBuffers(device_, commandPool_, 1, &cmd);
        vkDestroyBuffer(device_, staging, nullptr);
        vkFreeMemory(device_, stagingMem, nullptr);
    };

    createAndUpload(hudAtlas_, hudAtlasSampler_, hudRGBA, "hudAtlas");
    createAndUpload(legendAtlas_, legendAtlasSampler_, legendRGBA, "legendAtlas");
}

void App::destroyGuiResources()
{
    if (hudAtlas_.view)   vkDestroyImageView(device_, hudAtlas_.view, nullptr);
    if (hudAtlas_.image)  vkDestroyImage(device_, hudAtlas_.image, nullptr);
    if (hudAtlas_.memory) vkFreeMemory(device_, hudAtlas_.memory, nullptr);
    hudAtlas_ = {};

    if (legendAtlas_.view)   vkDestroyImageView(device_, legendAtlas_.view, nullptr);
    if (legendAtlas_.image)  vkDestroyImage(device_, legendAtlas_.image, nullptr);
    if (legendAtlas_.memory) vkFreeMemory(device_, legendAtlas_.memory, nullptr);
    legendAtlas_ = {};
}

void App::createGuiDescriptors()
{
    // Layout: set=0
    //  binding 0: game map SSBO
    //  binding 1: HUD atlas sampler
    //  binding 2: Legend atlas sampler
    if (!guiDescSetLayout_)
    {
        VkDescriptorSetLayoutBinding b0{};
        b0.binding = 0;
        b0.descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER;
        b0.descriptorCount = 1;
        b0.stageFlags = VK_SHADER_STAGE_FRAGMENT_BIT;

        VkDescriptorSetLayoutBinding b1{};
        b1.binding = 1;
        b1.descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
        b1.descriptorCount = 1;
        b1.stageFlags = VK_SHADER_STAGE_FRAGMENT_BIT;

        VkDescriptorSetLayoutBinding b2{};
        b2.binding = 2;
        b2.descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
        b2.descriptorCount = 1;
        b2.stageFlags = VK_SHADER_STAGE_FRAGMENT_BIT;

        VkDescriptorSetLayoutBinding bindings[3] = { b0, b1, b2 };

        VkDescriptorSetLayoutCreateInfo lci{VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO};
        // Must match the number of bindings provided.
        // A mismatch will read past the bindings array and can cause driver errors.
        lci.bindingCount = 3;
        lci.pBindings = bindings;
        vkCheck(vkCreateDescriptorSetLayout(device_, &lci, nullptr, &guiDescSetLayout_), "vkCreateDescriptorSetLayout(gui)");
    }

    if (guiDescPool_)
    {
        vkDestroyDescriptorPool(device_, guiDescPool_, nullptr);
        guiDescPool_ = VK_NULL_HANDLE;
    }

    VkDescriptorPoolSize ps[2] = {
        { VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, (uint32_t)MAX_FRAMES_IN_FLIGHT },
        { VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER, (uint32_t)MAX_FRAMES_IN_FLIGHT * 2u },
    };

    VkDescriptorPoolCreateInfo pci{VK_STRUCTURE_TYPE_DESCRIPTOR_POOL_CREATE_INFO};
    pci.maxSets = MAX_FRAMES_IN_FLIGHT;
    pci.poolSizeCount = 2;
    pci.pPoolSizes = ps;
    vkCheck(vkCreateDescriptorPool(device_, &pci, nullptr, &guiDescPool_), "vkCreateDescriptorPool(gui)");

    std::vector<VkDescriptorSetLayout> layouts(MAX_FRAMES_IN_FLIGHT, guiDescSetLayout_);
    VkDescriptorSetAllocateInfo ai{VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO};
    ai.descriptorPool = guiDescPool_;
    ai.descriptorSetCount = MAX_FRAMES_IN_FLIGHT;
    ai.pSetLayouts = layouts.data();

    std::vector<VkDescriptorSet> sets(MAX_FRAMES_IN_FLIGHT);
    vkCheck(vkAllocateDescriptorSets(device_, &ai, sets.data()), "vkAllocateDescriptorSets(gui)");
    for (uint32_t i = 0; i < MAX_FRAMES_IN_FLIGHT; ++i) guiDescSets_[i] = sets[i];

    for (uint32_t i = 0; i < MAX_FRAMES_IN_FLIGHT; ++i)
    {
        VkDescriptorBufferInfo bi{};
        bi.buffer = gameMapBuf_[i].buffer;
        bi.offset = 0;
        bi.range  = gameMapBuf_[i].size;

        VkDescriptorImageInfo ii{};
        ii.imageLayout = VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL;
        ii.imageView   = hudAtlas_.view;
        ii.sampler     = hudAtlasSampler_;

        VkDescriptorImageInfo li{};
        li.imageLayout = VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL;
        li.imageView   = legendAtlas_.view;
        li.sampler     = legendAtlasSampler_;

        VkWriteDescriptorSet w[3] = {};
        w[0] = {VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET};
        w[0].dstSet = guiDescSets_[i];
        w[0].dstBinding = 0;
        w[0].descriptorCount = 1;
        w[0].descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER;
        w[0].pBufferInfo = &bi;

        w[1] = {VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET};
        w[1].dstSet = guiDescSets_[i];
        w[1].dstBinding = 1;
        w[1].descriptorCount = 1;
        w[1].descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
        w[1].pImageInfo = &ii;

        w[2] = {VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET};
        w[2].dstSet = guiDescSets_[i];
        w[2].dstBinding = 2;
        w[2].descriptorCount = 1;
        w[2].descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
        w[2].pImageInfo = &li;

        vkUpdateDescriptorSets(device_, 3, w, 0, nullptr);
    }
}

