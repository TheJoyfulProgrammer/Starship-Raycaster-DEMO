void App::destroyGameResources()
{
    for (uint32_t i = 0; i < MAX_FRAMES_IN_FLIGHT; ++i)
    {
        {
            auto& b = gameMapBuf_[i];
            destroyBuffer(b.buffer, b.memory, &b.mapped);
            b.size = 0;
        }
        {
            auto& s = spriteBuf_[i];
            destroyBuffer(s.buffer, s.memory, &s.mapped);
            s.size = 0;
        }
    }

    // World atlas image (sampler destroyed in cleanup())
    if (worldAtlas_.view)   vkDestroyImageView(device_, worldAtlas_.view, nullptr);
    if (worldAtlas_.image)  vkDestroyImage(device_, worldAtlas_.image, nullptr);
    if (worldAtlas_.memory) vkFreeMemory(device_, worldAtlas_.memory, nullptr);
    worldAtlas_ = {};
}


void App::createGameDescriptors()
{
    // Layout: set=0
    //  binding 0: game map SSBO
    //  binding 1: world atlas sampler
    if (!gameDescSetLayout_)
    {
        VkDescriptorSetLayoutBinding b0{};
        b0.binding = 0;
        b0.descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER;
        b0.descriptorCount = 1;
        b0.stageFlags = VK_SHADER_STAGE_FRAGMENT_BIT;

        VkDescriptorSetLayoutBinding b1{};
        b1.binding = 1;
        b1.descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
        b1.descriptorCount = 1;
        b1.stageFlags = VK_SHADER_STAGE_FRAGMENT_BIT;

        VkDescriptorSetLayoutBinding b2{};
        b2.binding = 2;
        b2.descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER;
        b2.descriptorCount = 1;
        b2.stageFlags = VK_SHADER_STAGE_FRAGMENT_BIT;

        VkDescriptorSetLayoutBinding bindings[3] = { b0, b1, b2 };

        VkDescriptorSetLayoutCreateInfo lci{VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO};
        lci.bindingCount = 3;
        lci.pBindings = bindings;
        vkCheck(vkCreateDescriptorSetLayout(device_, &lci, nullptr, &gameDescSetLayout_), "vkCreateDescriptorSetLayout(game)");
    }

    if (gameDescPool_)
    {
        vkDestroyDescriptorPool(device_, gameDescPool_, nullptr);
        gameDescPool_ = VK_NULL_HANDLE;
    }

    VkDescriptorPoolSize poolSizes[2] = {};
    poolSizes[0].type = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER;
    poolSizes[0].descriptorCount = MAX_FRAMES_IN_FLIGHT * 2;
    poolSizes[1].type = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
    poolSizes[1].descriptorCount = MAX_FRAMES_IN_FLIGHT;

    VkDescriptorPoolCreateInfo pci{VK_STRUCTURE_TYPE_DESCRIPTOR_POOL_CREATE_INFO};
    pci.maxSets = MAX_FRAMES_IN_FLIGHT;
    pci.poolSizeCount = 2;
    pci.pPoolSizes = poolSizes;
    vkCheck(vkCreateDescriptorPool(device_, &pci, nullptr, &gameDescPool_), "vkCreateDescriptorPool(game)");

    std::vector<VkDescriptorSetLayout> layouts(MAX_FRAMES_IN_FLIGHT, gameDescSetLayout_);
    VkDescriptorSetAllocateInfo ai{VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO};
    ai.descriptorPool = gameDescPool_;
    ai.descriptorSetCount = MAX_FRAMES_IN_FLIGHT;
    ai.pSetLayouts = layouts.data();

    std::vector<VkDescriptorSet> sets(MAX_FRAMES_IN_FLIGHT);
    vkCheck(vkAllocateDescriptorSets(device_, &ai, sets.data()), "vkAllocateDescriptorSets(game)");
    for (uint32_t i = 0; i < MAX_FRAMES_IN_FLIGHT; ++i) gameDescSets_[i] = sets[i];

    for (uint32_t i = 0; i < MAX_FRAMES_IN_FLIGHT; ++i)
    {
        VkDescriptorBufferInfo bi{};
        bi.buffer = gameMapBuf_[i].buffer;
        bi.offset = 0;
        bi.range = gameMapBuf_[i].size;

        VkDescriptorImageInfo ii{};
        ii.sampler = worldAtlasSampler_;
        ii.imageView = worldAtlas_.view;
        ii.imageLayout = VK_IMAGE_LAYOUT_SHADER_READ_ONLY_OPTIMAL;

        VkWriteDescriptorSet writes[3] = {};

        writes[0] = {VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET};
        writes[0].dstSet = gameDescSets_[i];
        writes[0].dstBinding = 0;
        writes[0].descriptorCount = 1;
        writes[0].descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER;
        writes[0].pBufferInfo = &bi;

        writes[1] = {VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET};
        writes[1].dstSet = gameDescSets_[i];
        writes[1].dstBinding = 1;
        writes[1].descriptorCount = 1;
        writes[1].descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
        writes[1].pImageInfo = &ii;

        VkDescriptorBufferInfo sbi{};
        sbi.buffer = spriteBuf_[i].buffer;
        sbi.offset = 0;
        sbi.range = spriteBuf_[i].size;

        writes[2] = {VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET};
        writes[2].dstSet = gameDescSets_[i];
        writes[2].dstBinding = 2;
        writes[2].descriptorCount = 1;
        writes[2].descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER;
        writes[2].pBufferInfo = &sbi;

        vkUpdateDescriptorSets(device_, 3, writes, 0, nullptr);
    }
}

void App::destroyGameDescriptors()
{
    if (gameDescPool_) { vkDestroyDescriptorPool(device_, gameDescPool_, nullptr); gameDescPool_ = VK_NULL_HANDLE; }
    if (gameDescSetLayout_) { vkDestroyDescriptorSetLayout(device_, gameDescSetLayout_, nullptr); gameDescSetLayout_ = VK_NULL_HANDLE; }
    for (auto& ds : gameDescSets_) ds = VK_NULL_HANDLE;
}

