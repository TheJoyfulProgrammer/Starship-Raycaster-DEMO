    void vkCheck(VkResult r, const char* what)
    {
        if (r != VK_SUCCESS)
            throw std::runtime_error(std::string(what) + " (VkResult=" + std::to_string((int)r) + ")");
    }

    struct QueueFamilyIndices
    {
        bool graphicsFound = false;
        bool presentFound = false;
        uint32_t graphics = 0;
        uint32_t present  = 0;
    };

    QueueFamilyIndices findQueueFamilies(VkPhysicalDevice dev, VkSurfaceKHR surface)
    {
        QueueFamilyIndices out{};
        uint32_t count = 0;
        vkGetPhysicalDeviceQueueFamilyProperties(dev, &count, nullptr);
        std::vector<VkQueueFamilyProperties> props(count);
        vkGetPhysicalDeviceQueueFamilyProperties(dev, &count, props.data());

        for (uint32_t i=0;i<count;++i)
        {
            if (!out.graphicsFound && (props[i].queueFlags & VK_QUEUE_GRAPHICS_BIT))
            {
                out.graphicsFound = true;
                out.graphics = i;
            }

            VkBool32 presentSupport = VK_FALSE;
            vkGetPhysicalDeviceSurfaceSupportKHR(dev, i, surface, &presentSupport);
            if (!out.presentFound && presentSupport)
            {
                out.presentFound = true;
                out.present = i;
            }

            if (out.graphicsFound && out.presentFound) break;
        }
        return out;
    }

    struct SwapchainSupport
    {
        VkSurfaceCapabilitiesKHR caps{};
        std::vector<VkSurfaceFormatKHR> formats;
        std::vector<VkPresentModeKHR> presentModes;
    };

    SwapchainSupport querySwapchainSupport(VkPhysicalDevice dev, VkSurfaceKHR surface)
    {
        SwapchainSupport out{};
        vkGetPhysicalDeviceSurfaceCapabilitiesKHR(dev, surface, &out.caps);

        uint32_t fcount = 0;
        vkGetPhysicalDeviceSurfaceFormatsKHR(dev, surface, &fcount, nullptr);
        out.formats.resize(fcount);
        vkGetPhysicalDeviceSurfaceFormatsKHR(dev, surface, &fcount, out.formats.data());

        uint32_t mcount = 0;
        vkGetPhysicalDeviceSurfacePresentModesKHR(dev, surface, &mcount, nullptr);
        out.presentModes.resize(mcount);
        vkGetPhysicalDeviceSurfacePresentModesKHR(dev, surface, &mcount, out.presentModes.data());

        return out;
    }

    VkSurfaceFormatKHR chooseSwapSurfaceFormat(const std::vector<VkSurfaceFormatKHR>& formats)
    {
        for (auto& f : formats)
        {
            if (f.format == VK_FORMAT_B8G8R8A8_UNORM && f.colorSpace == VK_COLOR_SPACE_SRGB_NONLINEAR_KHR)
                return f;
        }
        return formats.empty() ? VkSurfaceFormatKHR{VK_FORMAT_B8G8R8A8_UNORM, VK_COLOR_SPACE_SRGB_NONLINEAR_KHR} : formats[0];
    }

    VkPresentModeKHR choosePresentMode(const std::vector<VkPresentModeKHR>& modes)
    {
        for (auto m : modes)
            if (m == VK_PRESENT_MODE_MAILBOX_KHR) return m;
        return VK_PRESENT_MODE_FIFO_KHR;
    }

    VkExtent2D chooseExtent(const VkSurfaceCapabilitiesKHR& caps, SDL_Window* window)
    {
        if (caps.currentExtent.width != UINT32_MAX)
            return caps.currentExtent;

        int w=0, h=0;
        SDL_GetWindowSizeInPixels(window, &w, &h);

        VkExtent2D e{};
        e.width = std::clamp<uint32_t>(uint32_t(std::max(1, w)), caps.minImageExtent.width, caps.maxImageExtent.width);
        e.height = std::clamp<uint32_t>(uint32_t(std::max(1, h)), caps.minImageExtent.height, caps.maxImageExtent.height);
        return e;
    }

    VkImageSubresourceRange fullColorRange()
    {
        VkImageSubresourceRange r{};
        r.aspectMask = VK_IMAGE_ASPECT_COLOR_BIT;
        r.baseMipLevel = 0;
        r.levelCount = 1;
        r.baseArrayLayer = 0;
        r.layerCount = 1;
        return r;
    }
