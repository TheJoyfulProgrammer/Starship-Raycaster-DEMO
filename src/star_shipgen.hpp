#pragma once

#include <cstdint>
#include <vector>

namespace Starship_Raycaster::shipgen
{
    // Output cell packing (must match the shaders + App::TileType semantics):
    // bits: [0..7]=type, [8..15]=doorOpen (or variant for non-doors), [16]=locked, [17..24]=zone

    struct Params
    {
        // Single-deck ship map (grid).
        uint32_t width  = 512;
        uint32_t height = 1024;
        uint32_t seed   = 1;

        // Reserved tuning knobs (kept for future iterations; this generator may ignore some/all of them).
        uint32_t minLeafW = 24;
        uint32_t minLeafH = 18;
        uint32_t roomPadMin = 1;
        uint32_t roomPadMax = 4;
        uint32_t spineThickness = 2;
        uint32_t localCorridorThickness = 3;
    };

    struct Result
    {
        uint32_t width  = 0;
        uint32_t height = 0;
        std::vector<uint32_t> cells;      // packed cell array (width*height)
        std::vector<uint32_t> doorCells;  // indices into cells

        // Suggested spawn point.
        float spawnX = 16.5f;
        float spawnY = 16.5f;
    };

    // Generates a ship-deck map with a north/south center corridor, edge margin corridors,
    // and deterministic themed areas.
    Result generate_bsp_ship(const Params& p);
}
